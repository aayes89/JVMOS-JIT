; draw_char_vram(char c, int x, int y, int color)
draw_char_vram:
    push ebp
    mov ebp, esp
    pusha

    movzx eax, byte [ebp + 8]   ; Carácter ASCII
    mov ebx, [ebp + 12]         ; X
    mov ecx, [ebp + 16]         ; Y
    mov edx, [ebp + 20]         ; Color

    ; offset = g_font_8x16 + (c * 16)
    shl eax, 4
    add eax, g_font_8x16

    ; PhysAddr = g_framebuffer + (y * pitch) + (x * 4)
    mov edi, [g_framebuffer]
    imul ecx, [g_pitch]
    shl ebx, 2
    add edi, ecx
    add edi, ebx

    mov ecx, 0                  ; Fila 0 a 15
.row_loop:
    cmp ecx, 16
    jge .done

    mov bl, [eax + ecx]         ; Byte con los 8 píxeles
    mov esi, 0                  ; Bit 0 a 7

.bit_loop:
    cmp esi, 8
    jge .next_row

    test bl, 0x80
    jz .skip_pixel

    mov [edi + esi * 4], edx     ; Pintar píxel en VRAM

.skip_pixel:
    shl bl, 1
    inc esi
    jmp .bit_loop

.next_row:
    add edi, [g_pitch]
    inc ecx
    jmp .row_loop

.done:
    popa
    mov esp, ebp
    pop ebp
    ret

